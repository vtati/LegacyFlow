def _hash_vault_token(token: str) -> str:
    return hashlib.sha256(token.encode("utf-8")).hexdigest()


def create_vault_share(
    conn: Any, *, actor_sub: str, matter_id: UUID, payload: sch.VaultShareCreate
) -> tuple[sch.VaultShareCreateOut, str]:
    """Create a vault share; return (response, raw token shown once)."""
    actor_id = _actor_id(actor_sub)
    scope = authz.require_matter_firm_role(conn, matter_id, actor_id, authz.STAFF_ROLES)
    matter = scope.matter

    raw_token = secrets.token_urlsafe(32)
    token_hash = _hash_vault_token(raw_token)
    expires_at = payload.expires_at or (datetime.now(UTC) + timedelta(days=30))
    if expires_at.tzinfo is None:
        expires_at = expires_at.replace(tzinfo=UTC)
    if expires_at <= datetime.now(UTC):
        raise ValidationAppError("expires_at must be in the future.")

    row = repo.insert_vault_share(
        conn,
        firm_id=UUID(str(matter["firm_id"])),
        matter_id=matter_id,
        label=payload.label,
        token_hash=token_hash,
        expires_at=expires_at,
        created_by_user_id=actor_id,
    )
    record_audit_event(
        conn,
        action="vault_share.created",
        resource_type="vault_shares",
        actor_user_id=actor_id,
        actor_type="user",
        firm_id=UUID(str(matter["firm_id"])),
        matter_id=matter_id,
        resource_id=UUID(str(row["id"])),
        after_summary={"label": payload.label},
    )
    out = sch.VaultShareCreateOut(
        id=row["id"],
        firm_id=row["firm_id"],
        matter_id=row["matter_id"],
        label=row["label"],
        expires_at=row["expires_at"],
        created_at=row["created_at"],
        access_token=raw_token,
    )
    return out, raw_token


def access_vault_share(conn: Any, payload: sch.VaultAccessIn) -> sch.VaultAccessOut:
    """Resolve a vault share by bearer token (no JWT required).

    Returns only the redacted matter summary — no household names, emails,
    or document content.
    """
    token_hash = _hash_vault_token(payload.token)
    row = repo.get_vault_share_by_hash(conn, token_hash)
    if row is None:
        raise NotFoundError("Vault share not found.")
    if row.get("revoked_at") is not None:
        raise GoneError("The vault share has been revoked.")
    expires_at = row["expires_at"]
    now = datetime.now(UTC)
    if expires_at.tzinfo is None:
        expires_at = expires_at.replace(tzinfo=UTC)
    if expires_at <= now:
        raise GoneError("The vault share has expired.")
    summary = repo.get_matter_vault_summary(conn, UUID(str(row["matter_id"])))
    if summary is None:
        raise NotFoundError("Vault share not found.")
    return sch.VaultAccessOut(
        matter_id=summary["id"],
        matter_status=str(summary["status"]),
        matter_title=str(summary["title"]),
        plan_type=str(summary["plan_type"]),
        jurisdiction_code=str(summary["jurisdiction_code"]),
    )


