def generate_instruction_letter(
    conn: Any, *, actor_sub: str, matter_id: UUID, payload: sch.InstructionLetterIn
) -> tuple[sch.DocumentPackageOut, list[sch.DocumentVersionOut]]:
    """Generate a nonbinding demo instruction letter for a matter.

    Family only: any household member may generate it. An
    ``instruction_letter`` template must exist (HTTP 422 when missing).
    The letter is watermarked DEMO ONLY and is never represented as
    legally valid.
    """
    actor_id = _actor_id(actor_sub)
    scope = authz.get_matter_scope(conn, matter_id, actor_id)
    if scope.via != "household":
        raise AuthorizationError("The instruction letter is generated by the family.")
    matter = scope.matter
    firm_id = UUID(str(matter["firm_id"]))

    template = repo.latest_template_by_type(conn, firm_id, "instruction_letter")
    if template is None:
        raise ValidationAppError("No instruction_letter template exists for this firm.")
    package = repo.find_package_for_template(conn, matter_id, UUID(str(template["id"])))
    if package is None:
        package = repo.insert_package(
            conn,
            firm_id=firm_id,
            matter_id=matter_id,
            template_id=UUID(str(template["id"])),
            created_by_user_id=actor_id,
        )

    context = _render_context(conn, matter)
    context["letter_text"] = payload.letter_text
    body = _merge_placeholders(_template_content_body(template), context)
    title = "Family Instruction Letter — DEMO (NONBINDING)"
    created = _render_package_versions(
        conn,
        package_id=UUID(str(package["id"])),
        matter=matter,
        actor_id=actor_id,
        template_name="instruction-letter",
        body=body,
        title=title,
    )
    package = repo.update_package_status(conn, UUID(str(package["id"])), "demo_released")
    record_audit_event(
        conn,
        action="instruction_letter.generated",
        resource_type="document_packages",
        actor_user_id=actor_id,
        actor_type="user",
        firm_id=firm_id,
        matter_id=matter_id,
        resource_id=UUID(str(package["id"])),
        after_summary={"nonbinding": True, "demo": True},
    )
    return _package_out(package), [_version_out(row) for row in created]


