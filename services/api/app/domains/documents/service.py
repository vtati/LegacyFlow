def _actor_id(actor_sub: str) -> UUID:
    """Resolve the JWT ``sub`` claim to the caller's profile id."""
    try:
        return UUID(actor_sub)
    except ValueError as exc:
        raise AuthError("The token subject is invalid.") from exc


