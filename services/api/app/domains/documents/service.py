def _render_context(conn: Any, matter: dict[str, Any]) -> dict[str, str]:
    """Build placeholder context from the matter's household/matter rows.

    Verified intake answers (confirmed interview replies and confirmed
    document extractions) are merged in as well, so ``{{question_key}}``
    placeholders in firm templates are pre-filled from verified facts.
    Curated keys above always win over answer keys on collision.
    """
    with conn.cursor() as cur:
        cur.execute("SELECT * FROM households WHERE id = %s", (str(matter["household_id"]),))
        household = cur.fetchone()
        cur.execute(
            "SELECT country_code, subdivision_code FROM jurisdictions WHERE id = %s",
            (str(matter.get("primary_jurisdiction_id")),),
        )
        jurisdiction = cur.fetchone()
    household_name = "the household"
    if household and household.get("display_name"):
        household_name = str(household["display_name"])
    matter_name = str(matter.get("title") or "the matter")
    jurisdiction_code = "US-VA"
    if jurisdiction and jurisdiction.get("country_code"):
        code = str(jurisdiction["country_code"])
        subdivision = str(jurisdiction.get("subdivision_code") or "")
        jurisdiction_code = f"{code}-{subdivision}".rstrip("-")
    today = datetime.now(UTC).strftime("%B %d, %Y")
    context = {
        "household_name": household_name,
        "matter_name": matter_name,
        "matter_title": matter_name,
        "jurisdiction_code": jurisdiction_code,
        "today": today,
        "firm_name": "the firm",
    }
    # Verified facts: only scalar answers become placeholders; complex values
    # are skipped rather than stringified into legal documents.
    for row in intake_repo.list_answers(conn, UUID(str(matter["id"]))):
        key = str(row["question_key"])
        if key in context:
            continue
        answer = row["answer"]
        if isinstance(answer, bool):
            context[key] = "Yes" if answer else "No"
        elif isinstance(answer, (str, int, float)):
            context[key] = str(answer)
    return context


#: Matches ``{{placeholder}}`` tokens left unfilled after a merge.
_UNFILLED_TOKEN = re.compile(r"\{\{\s*([a-zA-Z0-9_.]+)\s*\}\}")


def build_template_context(conn: Any, matter_id: UUID) -> dict[str, str]:
    """Build the full placeholder context for document templates.

    Public API for template rendering. Wraps the internal ``_render_context``
    and enhances it with structured person data (children lists, etc.) from
    the matter's household.

    Missing data is represented as ``___`` (blank line for attorney to fill)
    rather than leaving raw ``{{placeholder}}`` tokens in legal documents.
    """
    from ...domains.household import repository as household_repo

    with conn.cursor() as cur:
        cur.execute("SELECT * FROM matters WHERE id = %s", (str(matter_id),))
        matter_row = cur.fetchone()
    if matter_row is None:
        raise NotFoundError("Matter not found.")
    matter = dict(matter_row)

    context = _render_context(conn, matter)

    # Enhance with person data from the household.
    household_id = matter.get("household_id")
    if household_id:
        persons = household_repo.list_persons_for_household(conn, UUID(str(household_id)))
        children = []
        for p in persons:
            kind = str(p.get("kind") or "").lower()
            name = str(p.get("full_name") or "")
            if not name:
                continue
            dob = p.get("date_of_birth")
            dob_str = f" (DOB: {dob})" if dob else ""
            if kind in ("child", "minor_child", "son", "daughter"):
                children.append(f"{name}{dob_str}")
        if children:
            context["children_list"] = "\n".join(f"- {c}" for c in children)
        else:
            context["children_list"] = "___"

    # Replace any remaining unfilled placeholders with blank lines.
    # The _flag_unfilled_placeholders step still records them for attorney review.
    return context


def unfilled_placeholders(rendered_body: str) -> list[str]:
    """Placeholder names still present after merging the render context."""
    return sorted(set(_UNFILLED_TOKEN.findall(rendered_body)))


def _flag_unfilled_placeholders(
    conn: Any, *, matter: dict[str, Any], body: str, template_name: str
) -> None:
    """Record unmapped template placeholders as attorney questions.

    A placeholder with no verified fact behind it is never silently blanked:
    each one becomes an idempotent ``attorney_review`` escalation so it lands
    in the pre-review package.
    """
    missing = unfilled_placeholders(body)
    if not missing:
        return
    matter_id = UUID(str(matter["id"]))
    for name in missing:
        rule_id = f"document_unmapped_placeholder:{template_name}:{name}"
        if escalation_repo.open_escalation_exists(conn, matter_id, rule_id):
            continue
        escalation_repo.insert_escalation(
            conn,
            matter_id=matter_id,
            rule_id=rule_id,
            severity="review",
            outcome="attorney_review",
            facts_snapshot={
                "source": "document_assembly",
                "kind": "unmapped_placeholder",
                "placeholder": name,
                "template": template_name,
            },
        )


