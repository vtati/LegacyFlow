def send_reminders(conn: Any, *, limit: int = 100) -> dict[str, int]:
    """Worker actor: enqueue ``reminder.due`` notifications for due reminders.

    Reminders are firm/household/user scoped at insert time; the worker
    only acts on rows whose ``scheduled_for`` has passed and which have
    not been sent yet. Each due reminder marks ``sent_at`` and queues one
    notification to the reminder's user.
    """
    from ..review import repository as review_repo

    processed = 0
    queued = 0
    due = repo.list_due_reminders(conn, limit=limit)
    for reminder in due:
        payload = dict(reminder.get("payload") or {})
        review_repo.enqueue_notification(
            conn,
            firm_id=reminder["firm_id"],
            matter_id=reminder.get("matter_id"),
            template_key="reminder.due",
            payload={
                "reminder_id": str(reminder["id"]),
                "reminder_type": reminder["reminder_type"],
                "scheduled_for": str(reminder["scheduled_for"]),
                **payload,
            },
            recipient_user_id=reminder["user_id"],
        )
        repo.mark_reminder_sent(conn, reminder["id"])
        record_audit_event(
            conn,
            action="reminder.sent",
            resource_type="reminders",
            actor_user_id=None,
            actor_type="system",
            firm_id=reminder["firm_id"],
            matter_id=reminder.get("matter_id"),
            resource_id=reminder["id"],
            after_summary={"reminder_type": reminder["reminder_type"]},
        )
        processed += 1
        queued += 1
    return {"processed": processed, "queued": queued}


