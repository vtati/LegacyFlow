def _add_docx_header_footer(
    doc: DocxDocument, heading: str, disclaimer: str = DEMO_DISCLAIMER
) -> None:
    section = doc.sections[0]
    header = section.header
    header.is_linked_to_previous = False
    paragraph = header.paragraphs[0]
    paragraph.text = ""
    run = paragraph.add_run(heading)
    run.font.size = Pt(9)
    run.font.color.rgb = RGBColor(0x55, 0x55, 0x55)
    footer = section.footer
    footer.is_linked_to_previous = False
    paragraph = footer.paragraphs[0]
    paragraph.text = ""
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = paragraph.add_run(disclaimer)
    run.font.size = Pt(9)
    run.font.bold = True
    run.font.color.rgb = RGBColor(0xB0, 0x00, 0x00)


def _add_docx_diagonal_watermark(doc: DocxDocument, text: str) -> None:
    """Add a diagonal VML watermark to the document header.

    The watermark is built as an XML string and parsed with
    ``parse_xml`` — python-docx's ``OxmlElement`` cannot create the
    ``v:``/``o:`` prefixed VML elements directly because those prefixes
    are not in its namespace map, and lxml forbids setting ``xmlns:``
    attributes by hand.
    """
    from xml.sax.saxutils import escape

    from docx.oxml.ns import nsdecls, nsmap
    from docx.oxml.parser import parse_xml

    # Register the VML/Office namespaces so nsdecls() can declare them.
    nsmap.setdefault("v", "urn:schemas-microsoft-com:vml")
    nsmap.setdefault("o", "urn:schemas-microsoft-com:office:office")

    header = doc.sections[0].header
    header.is_linked_to_previous = False
    paragraph = header.paragraphs[0]

    watermark = escape(text)
    formulas = "".join(
        f'<v:f eqn="{eqn}"/>'
        for eqn in (
            "@0=3 8 @",
            "@1=3 6 @",
            "@2=1 8 @",
            "@3=3 8 @",
            "@4=3 6 @",
            "@5=1 8 @",
            "@6=0 @1",
            "@7=10800 @0",
            "@8=10800 @1",
        )
    )
    pict_xml = (
        f"<w:pict {nsdecls('w', 'v', 'o')}>"
        '<v:shapetype id="_x0000_t136" coordsize="21600,21600"'
        ' o:spt="136" adj="10800" path="m@7,l@8,m@5,21600l@6,21600e">'
        f"<v:formulas>{formulas}</v:formulas>"
        '<v:path o:connecttype="custom"'
        ' o:connectlocs="@9,0;@10,10800;@11,21600;@12,10800"'
        ' o:connectangles="270,180,90,0"/>'
        '<v:textpath on="t" fitshape="t"/>'
        '<v:handles><v:h position="#0,bottomRight" xrange="6629,14971"/></v:handles>'
        '<o:lock v:ext="edit" text="t"/>'
        "</v:shapetype>"
        '<v:shape id="demoWatermark" o:spid="_x0000_s1026" type="#_x0000_t136"'
        ' style="position:absolute;margin-left:0;margin-top:0;width:415pt;'
        "height:65pt;rotation:315;z-index:-25182;mso-position-horizontal:center;"
        "mso-position-horizontal-relative:margin;mso-position-vertical:center;"
        'mso-position-vertical-relative:margin"'
        ' o:allowincell="f" fillcolor="silver" stroked="f">'
        '<v:fill opacity=".5" color2="fill"/>'
        "<v:textpath "
        "style='font-family:\"Cambria\";font-size:1pt' "
        f'on="t" fitshape="t" string="{watermark}"/>'
        "</v:shape>"
        "</w:pict>"
    )
    pict = parse_xml(pict_xml)
    run = paragraph.add_run()
    run._r.append(pict)


def render_demo_docx(title: str, body: str, watermark_text: str) -> bytes:
    """Render a demo DOCX with header/footer and a diagonal watermark."""
    doc = Document()
    _add_docx_header_footer(doc, title)
    _add_docx_diagonal_watermark(doc, watermark_text)

    banner = doc.add_paragraph()
    banner.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = banner.add_run(DEMO_DISCLAIMER)
    run.bold = True
    run.font.size = Pt(14)
    run.font.color.rgb = RGBColor(0xB0, 0x00, 0x00)

    doc.add_heading(title, level=1)
    for paragraph_text in body.split("\n\n"):
        paragraph_text = paragraph_text.strip()
        if paragraph_text:
            doc.add_paragraph(paragraph_text)

    closing = doc.add_paragraph()
    closing.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = closing.add_run(
        "This is a demonstration document only. It is not legal advice and "
        "creates no attorney-client relationship."
    )
    run.italic = True
    run.font.size = Pt(9)

    buffer = io.BytesIO()
    doc.save(buffer)
    return buffer.getvalue()


def render_demo_pdf(title: str, body: str, watermark_text: str) -> bytes:
    """Render a demo PDF with header/footer and a diagonal watermark."""
    buffer = io.BytesIO()
    pdf = canvas.Canvas(buffer, pagesize=letter)
    width, height = letter

    def draw_chrome() -> None:
        pdf.saveState()
        pdf.setFont("Helvetica", 9)
        pdf.setFillColor(Color(0.33, 0.33, 0.33))
        pdf.drawString(inch, height - 0.6 * inch, title)
        pdf.setFont("Helvetica-Bold", 9)
        pdf.setFillColor(Color(0.69, 0.0, 0.0))
        pdf.drawCentredString(width / 2, 0.6 * inch, DEMO_DISCLAIMER)
        pdf.setFont("Helvetica-Bold", 48)
        pdf.setFillColor(Color(0.75, 0.75, 0.75, alpha=0.35))
        pdf.saveState()
        pdf.translate(width / 2, height / 2)
        pdf.rotate(45)
        pdf.drawCentredString(0, 0, watermark_text)
        pdf.restoreState()
        pdf.restoreState()

    draw_chrome()
    text = pdf.beginText(inch, height - 1.2 * inch)
    text.setFont("Helvetica-Bold", 16)
    text.textLine(DEMO_DISCLAIMER)
    text.setFont("Helvetica-Bold", 14)
    text.textLine(title)
    text.setFont("Helvetica", 11)
    text.textLine("")
    max_width = width - 2 * inch
    for raw_paragraph in body.split("\n\n"):
        words = raw_paragraph.strip().split()
        line = ""
        for word in words:
            candidate = f"{line} {word}".strip()
            if pdf.stringWidth(candidate, "Helvetica", 11) > max_width and line:
                text.textLine(line)
                line = word
            else:
                line = candidate
        if line:
            text.textLine(line)
        text.textLine("")
        if text.getY() < inch:
            pdf.drawText(text)
            pdf.showPage()
            draw_chrome()
            text = pdf.beginText(inch, height - 1.2 * inch)
            text.setFont("Helvetica", 11)
    text.setFont("Helvetica-Oblique", 9)
    text.textLine(
        "This is a demonstration document only. It is not legal advice and "
        "creates no attorney-client relationship."
    )
    pdf.drawText(text)
    pdf.showPage()
    pdf.save()
    return buffer.getvalue()


def render_template_content(template_body: str, context: dict[str, str]) -> str:
    """Substitute ``{{placeholder}}`` tokens; unknown tokens are left intact."""
    merged = template_body
    for key, value in context.items():
        merged = merged.replace("{{" + key + "}}", value)
    return merged


def _merge_placeholders(template_body: str, context: dict[str, str]) -> str:
    """Internal alias kept for readability at call sites."""
    return render_template_content(template_body, context)


