def _asset_label(asset: dict[str, Any]) -> str:
    return str(asset.get("label") or asset.get("asset_type") or "asset")


def generate_funding_tasks(
    conn: Any, *, actor_sub: str, matter_id: UUID
) -> list[sch.FundingTaskOut]:
    """Generate funding tasks from playbooks × household assets (idempotent).

    Each asset is mapped from the database asset vocabulary to the
    content-pack funding-playbook vocabulary; every playbook covering the
    asset creates one task (e.g. a bank account gets both
    ``bank-tod-podb`` and ``general-beneficiary-alignment``).
    """
    actor_id = _actor_id(actor_sub)
    scope = authz.require_matter_firm_role(conn, matter_id, actor_id, authz.STAFF_ROLES)
    matter = scope.matter
    profile = _load_execution_profile(conn, matter)
    assets = repo.list_assets_for_matter(conn, matter_id)

    created: list[tuple[dict[str, Any], dict[str, Any]]] = []
    for asset in assets:
        vocab = _ASSET_TYPE_TO_PACK_VOCAB.get(str(asset.get("asset_type") or ""))
        if not vocab:
            continue
        asset_id = UUID(str(asset["id"]))
        for playbook in profile.funding_playbooks:
            if vocab not in playbook.get("asset_types", []):
                continue
            if repo.funding_task_exists(conn, matter_id, asset_id, playbook["playbook_id"]):
                continue
            row = repo.insert_funding_task(
                conn,
                firm_id=UUID(str(matter["firm_id"])),
                matter_id=matter_id,
                asset_id=asset_id,
                task_type=playbook["playbook_id"],
                title=f"{playbook['title']} — {_asset_label(asset)}",
            )
            created.append((row, playbook))
    for row, _playbook in created:
        record_audit_event(
            conn,
            action="funding_task.created",
            resource_type="funding_tasks",
            actor_user_id=actor_id,
            actor_type="user",
            firm_id=UUID(str(matter["firm_id"])),
            matter_id=matter_id,
            resource_id=UUID(str(row["id"])),
            after_summary={"task_type": row["task_type"]},
        )
    return [_funding_out(row, playbook=playbook) for row, playbook in created]


def list_funding_tasks(conn: Any, *, actor_sub: str, matter_id: UUID) -> list[sch.FundingTaskOut]:
    """List a matter's funding tasks (firm staff or household member)."""
    actor_id = _actor_id(actor_sub)
