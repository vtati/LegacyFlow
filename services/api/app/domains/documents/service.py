"""Application services for the documents domain (Slice 4).

Authorization summary (callers are identified by JWT ``sub`` = profiles.id):
  * Templates: create is firm_admin only; list/get are firm staff. The
    caller's firm comes from ``authz.get_user_firm_id`` (MVP: one firm).
  * Packages / demo generation: firm staff on the matter
    (``authz.require_matter_firm_role``), AND the ``document_assembly``
    feature flag must be effective for (firm_id, pack_id), AND the matter's
    pack manifest must declare the ``document_assembly`` capability —
    otherwise the call fails closed with HTTP 409
    (``document_assembly_disabled``).
  * Production release: ALWAYS fails closed with HTTP 409
    (``production_release_unavailable``) — real release needs Slice 5+
    attorney gates, so no release path exists in this slice.
  * Signing checklists: generated by firm staff from the matter pack's
    execution profile; attestations are household-member client
    attestations (non-certifying), stored inside the checklist's jsonb
    payload (Track A4 owns the DDL; there is no attestations table).
  * Funding tasks: generated by firm staff from pack funding playbooks ×
    the matter household's assets; updates are firm staff or household
    primary_client/collaborator.
  * Vault shares: created/revoked by firm staff; access is by bearer
    token only (no JWT). Only the SHA-256 token hash is stored.
  * Family instruction letter: nonbinding demo — generated with the
    same DEMO ONLY watermarking; never legally valid.

Errors follow the codebase RFC 7807 convention (``app.core.errors``);
the routers surface them via the ``AppError`` handler in ``app.main``.

Persistence follows Track A4's migration
(``20260927030000_files_documents_slice4.sql``): rendered files live in
the server-side document storage directory (``Settings.DOCUMENT_STORAGE_DIR``)
with ``file_uploads`` rows pointing at them, and immutable
``document_versions`` rows reference those uploads.
"""

