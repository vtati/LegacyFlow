def update_funding_task(
    conn: Any,
    *,
    actor_sub: str,
    task_id: UUID,
    status: str | None = None,
    evidence_file_id: UUID | None = None,
    evidence_upload: tuple[str, bytes, str] | None = None,
) -> sch.FundingTaskOut:
    """Update a funding task's status and/or evidence (firm staff or household member).

    Accepts either a status change, an existing ``evidence_file_id``, or a
    new evidence upload ``(filename, content, content_type)``.
    """
    actor_id = _actor_id(actor_sub)
    task = repo.get_funding_task(conn, task_id)
    if task is None:
        raise NotFoundError("Funding task not found.")
    scope = authz.get_matter_scope(conn, UUID(str(task["matter_id"])), actor_id)
    if scope.via == "household" and scope.household_role not in HOUSEHOLD_ATTEST_ROLES:
        raise AuthorizationError("Not authorized to update this funding task.")
    if status is not None and status not in ("pending", "in_progress", "completed"):
        raise ValidationAppError(f"Invalid funding task status: {status!r}.")
    if status is None and evidence_file_id is None and evidence_upload is None:
        raise ValidationAppError("Nothing to update.")

    matter = scope.matter
    uploaded_name: str | None = None
    uploaded_digest: str | None = None
    if evidence_upload is not None:
        uploaded_name, content, content_type = evidence_upload
        uploaded_digest = hashlib.sha256(content).hexdigest()
        stored_path = _store_file(
            f"evidence-{task_id}",
            "pdf" if content_type == PDF_MIME else "docx",
            content,
        )
        upload = repo.insert_file_upload(
            conn,
            firm_id=UUID(str(matter["firm_id"])),
            household_id=UUID(str(matter["household_id"])),
            matter_id=UUID(str(matter["id"])),
            uploader_user_id=actor_id,
            original_filename=uploaded_name,
            stored_path=stored_path,
            mime_type=content_type,
            size_bytes=len(content),
            scan_status="clean",
            scan_detail="Household-supplied evidence file.",
        )
        evidence_file_id = UUID(str(upload["id"]))
    elif evidence_file_id is not None:
        existing_upload = repo.get_file_upload(conn, evidence_file_id)
        if existing_upload is None or UUID(str(existing_upload["firm_id"])) != UUID(
            str(matter["firm_id"])
        ):
            raise NotFoundError("Evidence file not found.")

    row = repo.update_funding_task(conn, task_id, status=status, evidence_file_id=evidence_file_id)
    playbooks = _funding_playbooks_by_id(scope.matter)
    record_audit_event(
        conn,
        action="funding_task.updated",
        resource_type="funding_tasks",
        actor_user_id=actor_id,
        actor_type="user",
        firm_id=UUID(str(matter["firm_id"])),
        matter_id=UUID(str(matter["id"])),
        resource_id=task_id,
        after_summary={
            "status": status,
            "evidence_file_id": str(evidence_file_id) if evidence_file_id else None,
            "evidence_file_name": uploaded_name,
            "evidence_sha256": uploaded_digest,
        },
    )
    return _funding_out(
        row,
        _evidence_out(conn, row.get("evidence_file_id")),
        playbook=playbooks.get(str(row["task_type"])),
    )


