def _storage_dir() -> Path:
    """Server-side directory where rendered files are stored."""
    directory = get_settings().document_storage_dir
    directory.mkdir(parents=True, exist_ok=True)
    return directory


def _store_file(filename_stem: str, file_format: str, content: bytes) -> str:
    """Write rendered bytes to the storage dir; return the stored path."""
    path = _storage_dir() / f"{filename_stem}-{uuid.uuid4().hex}.{SUFFIX_BY_FORMAT[file_format]}"
    path.write_bytes(content)
    return str(path)


def _file_format_from_upload(row: dict[str, Any]) -> Literal["docx", "pdf"]:
    """Derive the file format from an upload row's mime/filename."""
    mime = str(row.get("mime_type") or "")
    if mime == PDF_MIME:
        return "pdf"
    name = str(row.get("original_filename") or "")
    if name.lower().endswith(".pdf"):
        return "pdf"
    return "docx"


def _version_out(row: dict[str, Any]) -> sch.DocumentVersionOut:
    file_format = _file_format_from_upload(row)
    watermark = row.get("watermark_text")
    return sch.DocumentVersionOut(
        id=row["id"],
        package_id=row["package_id"],
        version=int(row["version"]),
        file_format=file_format,
        file_name=str(row["original_filename"]),
        content_type=str(row["mime_type"]),
        watermark_text=watermark,
        is_demo=watermark is not None,
        download_url=f"/v1/document-versions/{row['id']}/download",
        created_at=row["created_at"],
    )


def _checklist_out(row: dict[str, Any]) -> sch.SigningChecklistOut:
    checklist = row.get("checklist") or {}
    if isinstance(checklist, str):
        checklist = json.loads(checklist)
    attestations = [
        sch.AttestationOut(
            statement_key=entry["statement_key"],
            attested=bool(entry["attested"]),
            attested_at=entry["attested_at"],
            attested_by_user_id=entry["attested_by_user_id"],
        )
        for entry in checklist.get("attestations", [])
    ]
    return sch.SigningChecklistOut(
        id=row["id"],
        firm_id=row["firm_id"],
        matter_id=row["matter_id"],
        execution_profile_id=str(checklist.get("execution_profile_id", "")),
        document_type=str(checklist.get("document_type", "")),
        requirements=dict(checklist.get("requirements", {})),
        items=[
            sch.SigningChecklistItemOut(
                key=item["key"], label=item["label"], detail=item.get("detail")
            )
            for item in checklist.get("items", [])
        ],
        attestations=attestations,
        completed_at=row.get("completed_at"),
        created_at=row["created_at"],
    )


def _evidence_out(conn: Any, evidence_file_id: Any) -> sch.FundingEvidenceOut | None:
    """Build evidence metadata from the linked file_upload row (if any)."""
    if evidence_file_id is None:
        return None
    upload = repo.get_file_upload(conn, UUID(str(evidence_file_id)))
    if upload is None:
        return None
    path = Path(str(upload["stored_path"]))
    digest = hashlib.sha256(path.read_bytes()).hexdigest() if path.is_file() else None
    return sch.FundingEvidenceOut(
        file_name=str(upload["original_filename"]),
        size_bytes=int(upload["size_bytes"]),
        sha256=digest,
    )


